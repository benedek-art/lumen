#!/usr/bin/env python3
"""Generate renderlab/CONTROLS.md from the code.

  LUMEN_RENDERLAB_CONTROLS=/tmp/controls.json swift test --filter RenderLabControlsDump
  python3 renderlab/gen-controls.py /tmp/controls.json > renderlab/CONTROLS.md

Ranges and neutrals come from ProofRegistry (the proof lane's declared slider travel);
recipe paths come from diffing the recipe's JSON encoding; the "source note" column is
the trailing comment on the field's declaration in Sources/LumenCore/Recipe.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = sorted((ROOT / "Sources/LumenCore/Recipe").glob("*.swift"))


def parse_structs():
    structs = {}
    for f in SOURCES:
        current = None
        for line in f.read_text().splitlines():
            m = re.match(r"^public (?:struct|final class|enum) (\w+)", line)
            if m:
                current = structs.setdefault(m.group(1), {})
                continue
            m = re.match(r"^\s{4}public var (\w+): ([\w\[\]?.<>: ,]+?)\s*(?://\s*(.*))?$", line)
            if m and current is not None:
                typ = m.group(2).strip().rstrip("?").strip("[]").rstrip("?")
                current[m.group(1)] = (typ, (m.group(3) or "").strip())
    return structs


STRUCTS = parse_structs()
ROOT_TYPE = {"develop": "Develop", "look": "Look", "masks": "Mask", "maskGroups": "MaskGroup",
             "pipelineVersion": None}


def note(path):
    parts = path.split(".")
    typ = "Recipe"
    comment = ""
    for p in parts:
        if p.isdigit():
            continue
        fields = STRUCTS.get(typ, {})
        if p in fields:
            typ, comment = fields[p]
        elif typ == "Recipe" and p in ROOT_TYPE:
            typ, comment = ROOT_TYPE[p], ""
        else:
            return ""
    return comment.replace("|", "/")


def fmt(v):
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return json.dumps(v, ensure_ascii=False).replace("|", "/")


def main():
    d = json.loads(Path(sys.argv[1]).read_text())
    out = []
    w = out.append
    w("# Render lab control reference")
    w("")
    w("Generated by `renderlab/gen-controls.py` from `RenderLabControlsDump` (ProofRegistry + the "
      "recipe's own JSON encoding). Do not edit by hand. Use the **recipe path** as a key in a "
      "manifest `recipe` patch or as a sweep `path`. Range is the proof lane's declared travel; "
      "the app may accept values beyond it (the patch reports any value the recipe decoder "
      "changed under `recipeAdjusted`).")
    w("")
    w("Defaults are `Recipe()` (base `blank`). Base `imported` (the default) is what the app "
      "gives a new RAW: the same, plus ISO-dependent noise reduction (table at the end).")
    w("")
    covered = set()
    panels = {}
    for c in d["controls"]:
        panels.setdefault(c["panel"], []).append(c)
    for panel, items in panels.items():
        w(f"## {panel}")
        w("")
        w("| control | recipe path | range | neutral | default | also sets | source note |")
        w("|---|---|---|---|---|---|---|")
        for c in items:
            covered.update(c["paths"])
            paths = "<br>".join(f"`{p}`" for p in c["paths"]) or "(none)"
            default = "<br>".join(fmt(c["defaults"].get(p)) for p in c["paths"])
            also = "<br>".join(f"`{k}`={fmt(v)}" for k, v in sorted(c["alsoSets"].items()))
            notes = "<br>".join(filter(None, (note(p) for p in c["paths"])))
            w(f"| {c['name']} (`{c['id']}`) | {paths} | {fmt(c['low'])} … {fmt(c['high'])} | "
              f"{fmt(c['neutral'])} | {default} | {also} | {notes} |")
        w("")
    w("## Enumerated values")
    w("")
    for k, v in d["enums"].items():
        w(f"- `{k}`: {', '.join(fmt(x) for x in v)}")
    w(f"- charts (photo ids): {', '.join(d['charts'])}")
    w("")
    w("## Fields with no proof-registry entry")
    w("")
    w("Every other leaf of the default recipe, with its default. Ranges here are the source note "
      "only; nothing has declared a travel for them.")
    w("")
    w("| recipe path | default | source note |")
    w("|---|---|---|")
    for leaf in d["defaultRecipe"]:
        if leaf["path"] not in covered:
            w(f"| `{leaf['path']}` | {fmt(leaf['default'])} | {note(leaf['path'])} |")
    w("")
    w("## Optional blocks (absent by default; a patch that sets any key creates the block)")
    w("")
    w("| recipe path | value once present | source note |")
    w("|---|---|---|")
    for leaf in d["optionalBlocks"]:
        w(f"| `{leaf['path']}` | {fmt(leaf['whenPresent'])} | {note(leaf['path'])} |")
    w("")
    w("Also optional, not shown: `look.lut` (`ref`, `name`, `tap`, `amount`; see README for "
      "registering a .cube), `develop.raw.temp` / `develop.raw.tint` (absent = as shot), "
      "`develop.denoise.raw` (`enabled`, `strength`, `model`), `look.render.contrast` / `skew` / "
      "`huePreservation` / `blackTarget` / `whiteTarget` (absent = preset value), "
      "`look.filmLab.halationSize` / `halationRedness`, `develop.geometry.upright`, "
      "`develop.geometry.lens.defringe`.")
    w("")
    w("## Noise reduction a new RAW starts with (base `imported`), by capture ISO")
    w("")
    for iso, dn in d["importedDenoise"].items():
        w(f"- {iso}: `{json.dumps(dn, sort_keys=True)}`")
    print("\n".join(out))


if __name__ == "__main__":
    main()
